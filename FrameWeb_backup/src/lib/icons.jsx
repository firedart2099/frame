/**
 * A marca do Frame: a moldura de duas bordas com as diagonais nos cantos,
 * igual ao ícone do app. Em SVG porque ela aparece de 20px (topo) a 120px
 * (hero) — PNG borraria em algum desses tamanhos.
 *
 * `stroke` herda currentColor, então ela é branca no preto sem precisar de
 * duas versões do arquivo.
 */
export function Logo({ size = 28, strokeWidth = 4.5, style, className, title }) {
  return (
    <svg
      width={size}
      height={(size * 86) / 100}
      viewBox="0 0 100 86"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      role={title ? 'img' : undefined}
      aria-label={title}
      aria-hidden={title ? undefined : 'true'}
      focusable="false"
      style={{ flex: '0 0 auto', ...style }}
      className={className}
    >
      <rect x="3.5" y="3.5" width="93" height="79" rx="9" />
      <rect x="18" y="16" width="64" height="54" rx="1.5" />
      <path d="M3.5 3.5 18 16M96.5 3.5 82 16M3.5 82.5 18 70M96.5 82.5 82 70" />
    </svg>
  );
}

export default function Icon({ name, size = 18, strokeWidth = 1.9, fill = 'none', style, className }) {
  const shape = P[name];
  if (!shape) return null;
  const solid = name === 'play' || name === 'zap' || name === 'star' || name === 'selo';
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill={solid ? 'currentColor' : fill}
      stroke="currentColor"
      strokeWidth={solid ? 0 : strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      style={{ flex: '0 0 auto', ...style }}
      className={className}
    >
      {shape}
    </svg>
  );
}
